const dicts = { English: EN, Tamil: TA, Hindi: HINDI, Telugu: EN, Kannada: EN, Malayalam: EN, Bengali: EN };

export function t(key, lang = 'English') {
  const parts = key.split('.');
  let val = dicts[lang]?.[parts[0]];
  if (!val) val = EN[parts[0]];
  for (let i = 1; i < parts.length; i++) {
    if (!val || typeof val !== 'object') return key;
    val = val[parts[i]];
  }
  return typeof val === 'string' ? val : key;
}

export function formatMsg(msg, vars) {
  if (!vars) return msg;
  let out = msg;
  for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
  return out;
}
